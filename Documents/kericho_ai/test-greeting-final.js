const http = require('http');

async function sendWebhook(testCase) {
  return new Promise((resolve) => {
    const data = JSON.stringify({
      entry: [{
        changes: [{
          value: {
            messages: [{
              from: testCase.from,
              text: {
                body: testCase.message
              }
            }]
          }
        }]
      }]
    });

    const options = {
      hostname: 'localhost',
      port: 3000,
      path: '/webhook',
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Content-Length': data.length,
      },
    };

    const req = http.request(options, (res) => {
      res.on('data', () => {});
      res.on('end', () => {
        setTimeout(() => {
          // Check logs for response
          const fs = require('fs');
          try {
            const logs = fs.readFileSync('/home/lod/Documents/kericho_ai/logs/combined-2026-05-13.log', 'utf-8');
            const lastLines = logs.split('\n').slice(-20).join('\n');
            
            let foundResponse = false;
            for (const expectedStr of testCase.expectedContains) {
              if (lastLines.includes(expectedStr)) {
                foundResponse = true;
                break;
              }
            }

            resolve({
              testCase,
              foundResponse,
              lastLines: logs.split('\n').slice(-5).filter(l => l.includes(testCase.message) || l.includes('"message"'))
            });
          } catch (e) {
            resolve({ testCase, error: e.message });
          }
        }, 1500);
      });
    });

    req.on('error', (error) => {
      resolve({ testCase, error: error.message });
    });

    req.write(data);
    req.end();
  });
}

